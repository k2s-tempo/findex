"""
tokenize(): потоковий токенізатор із Unicode-нормалізацією.

Правила токенізації (задокументовані рішення):
1. Unicode-нормалізація: NFKC — приводить сумісні варіанти символів
   до єдиної форми (наприклад, лігатури, різні форми лапок) та
   спрощує подальшу обробку. Обрано NFKC (а не NFC), бо корпус —
   англомовні тексти з Gutenberg, де можуть траплятись типографські
   варіанти символів (напр. "fi"-лігатура), і їх варто розкладати.
2. Регістр: все приводиться до нижнього (lowercase) — пошук
   регістронезалежний.
3. Апострофи: розглядаються як частина слова, якщо вони всередині
   літер (don't, it's, O'Brien) — токен лишається одним цілим
   словом. Апостроф на межі слова (лапки навколо репліки) —
   відкидається.
4. Дефіси: слово з дефісом всередині (self-driving, well-known)
   лишається ОДНИМ токеном. Це рішення: дефіс частіше з'єднує
   складові одного поняття, ніж розділяє незалежні слова.
5. Цифри: числа зберігаються як окремі токени (напр. "1580" — 
   токен), але не змішуються з літерами в одному токені.
6. Пунктуація (крім апострофа й дефіса всередині слова) —
   повністю відкидається і не є токеном.

Токенізатор — генератор: обробляє текст і видає токени по одному,
не будуючи проміжний список усіх токенів документа.
"""
import re
import unicodedata

# Токен: послідовність літер/цифр, всередині якої можуть бути
# одиничні апострофи або дефіси, що з'єднують літерні частини.
_TOKEN_RE = re.compile(
    r"[^\W\d_]+(?:['\-][^\W\d_]+)*"   # слова з апострофами/дефісами всередині
    r"|\d+",                          # або числа окремо
    re.UNICODE,
)


def tokenize(text: str):
    """
    Генератор: приймає рядок тексту, повертає токени один за одним.

    >>> list(tokenize("Don't stop self-driving in 1580!"))
    ["don't", 'stop', 'self-driving', 'in', '1580']
    """
    normalized = unicodedata.normalize("NFKC", text)
    lowered = normalized.lower()

    for match in _TOKEN_RE.finditer(lowered):
        yield match.group()